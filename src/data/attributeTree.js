function hasAnyFilterable(node) {
  if (node.filterId) return true
  if (node.children) return node.children.some(hasAnyFilterable)
  return false
}

// Flatten all filterable leaf nodes with full path, for search
export function flattenFilterable(nodes, path = []) {
  const results = []
  for (const node of nodes) {
    const nodePath = [...path, node.label]
    if (node.children) {
      results.push(...flattenFilterable(node.children, nodePath))
    } else if (node.filterId) {
      results.push({ ...node, path: nodePath })
    }
  }
  return results
}

// Flatten ALL leaf nodes (filterable and informational) for comprehensive search
export function flattenAll(nodes, path = []) {
  const results = []
  for (const node of nodes) {
    const nodePath = [...path, node.label]
    if (node.children) {
      results.push(...flattenAll(node.children, nodePath))
    } else {
      results.push({ ...node, path: nodePath })
    }
  }
  return results
}

